package main

import (
	"bytes"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"time"

	"github.com/spf13/cobra"

	"github.com/eukalpia/unio/internal/config"
)

// Sizes of generated random material. Each value is checked against the
// configuration rules before it is accepted, so `unio init` cannot produce
// credentials that the server would reject.
const (
	clusterSecretBytes = 48 // base64url gives 64 characters
	rootUserHexBytes   = 10 // "unio-" plus 20 hex characters
	rootPasswordBytes  = 36 // base64url gives 48 characters
	metricsTokenBytes  = 48
	generationAttempts = 5
	credentialFileMode = 0o600
	credentialFileDesc = "0600"
)

// credentials are the generated secrets of one node or cluster.
type credentials struct {
	clusterSecret string
	rootUser      string
	rootPassword  string
	metricsToken  string
}

// newInitCmd builds "unio init", which writes a new set of credentials to an
// env-format file with mode 0600. It refuses to overwrite an existing file, and
// it never prints the secrets.
func newInitCmd(a app) *cobra.Command {
	var output string
	cmd := &cobra.Command{
		Use:   "init",
		Short: "generate cluster secret and root credentials into a 0600 env file",
		Long: "init writes UNIO_CLUSTER_SECRET, UNIO_ROOT_USER, UNIO_ROOT_PASSWORD and UNIO_METRICS_TOKEN " +
			"to a new file. The file is created with mode 0600 and is never overwritten. The secrets are not printed.",
		Args: cobra.NoArgs,
		RunE: func(_ *cobra.Command, _ []string) error {
			creds, err := generateCredentials(rand.Reader)
			if err != nil {
				return err
			}
			if err := createNewFile(output, formatEnvFile(creds, time.Now().UTC())); err != nil {
				return err
			}
			_, err = fmt.Fprintf(a.stdout, "wrote credentials to %s (mode %s); the secrets were not printed\n",
				output, credentialFileDesc)
			return err
		},
	}
	cmd.Flags().StringVar(&output, "output", "", "path of the new credentials file (must not exist)")
	_ = cmd.MarkFlagRequired("output")
	return cmd
}

// generateCredentials creates credentials from random and checks each value
// against the configuration rules. The source is a parameter so tests can
// supply a fixed reader.
func generateCredentials(random io.Reader) (credentials, error) {
	var creds credentials
	var err error
	if creds.clusterSecret, err = generateChecked(func() (string, error) {
		return randomString(random, clusterSecretBytes, base64.RawURLEncoding.EncodeToString)
	}, config.CheckSecretValue); err != nil {
		return credentials{}, fmt.Errorf("cluster secret: %w", err)
	}
	if creds.rootUser, err = generateChecked(func() (string, error) {
		raw, err := randomString(random, rootUserHexBytes, hex.EncodeToString)
		if err != nil {
			return "", err
		}
		return "unio-" + raw, nil
	}, config.CheckRootUser); err != nil {
		return credentials{}, fmt.Errorf("root user: %w", err)
	}
	if creds.rootPassword, err = generateChecked(func() (string, error) {
		return randomString(random, rootPasswordBytes, base64.RawURLEncoding.EncodeToString)
	}, func(v string) error {
		return config.CheckRootPassword(creds.rootUser, v)
	}); err != nil {
		return credentials{}, fmt.Errorf("root password: %w", err)
	}
	if creds.metricsToken, err = generateChecked(func() (string, error) {
		return randomString(random, metricsTokenBytes, base64.RawURLEncoding.EncodeToString)
	}, config.CheckSecretValue); err != nil {
		return credentials{}, fmt.Errorf("metrics token: %w", err)
	}
	return creds, nil
}

// generateChecked calls gen until check accepts the value, up to generationAttempts times.
func generateChecked(gen func() (string, error), check func(string) error) (string, error) {
	var last error
	for range generationAttempts {
		v, err := gen()
		if err != nil {
			return "", err
		}
		if last = check(v); last == nil {
			return v, nil
		}
	}
	return "", fmt.Errorf("could not generate a valid value in %d attempts: %w", generationAttempts, last)
}

// randomString reads n random bytes from random and encodes them with encode.
func randomString(random io.Reader, n int, encode func([]byte) string) (string, error) {
	buf := make([]byte, n)
	if _, err := io.ReadFull(random, buf); err != nil {
		return "", fmt.Errorf("read random bytes: %w", err)
	}
	return encode(buf), nil
}

// formatEnvFile renders creds as an env file that compose and the shell can
// read. Every value uses an alphabet that needs no quoting.
func formatEnvFile(creds credentials, when time.Time) []byte {
	var b bytes.Buffer
	_, _ = fmt.Fprintf(&b, "# Generated by unio init at %s. Keep this file secret: mode %s, never commit it.\n",
		when.Format(time.RFC3339), credentialFileDesc)
	_, _ = fmt.Fprintf(&b, "UNIO_CLUSTER_SECRET=%s\n", creds.clusterSecret)
	_, _ = fmt.Fprintf(&b, "UNIO_ROOT_USER=%s\n", creds.rootUser)
	_, _ = fmt.Fprintf(&b, "UNIO_ROOT_PASSWORD=%s\n", creds.rootPassword)
	_, _ = fmt.Fprintf(&b, "UNIO_METRICS_TOKEN=%s\n", creds.metricsToken)
	return b.Bytes()
}

// createNewFile writes data to a new file with mode 0600. It fails if the file
// already exists, and removes the partial file on a write error.
func createNewFile(path string, data []byte) error {
	if path == "" {
		return errors.New("--output is required")
	}
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, credentialFileMode)
	if err != nil {
		if errors.Is(err, fs.ErrExist) {
			return fmt.Errorf("refusing to overwrite %s: the file already exists", path)
		}
		return fmt.Errorf("cannot create %s: %w", path, err)
	}
	if _, err := f.Write(data); err != nil {
		_ = f.Close()
		_ = os.Remove(path)
		return fmt.Errorf("cannot write %s: %w", path, err)
	}
	if err := f.Sync(); err != nil {
		_ = f.Close()
		_ = os.Remove(path)
		return fmt.Errorf("cannot flush %s: %w", path, err)
	}
	if err := f.Close(); err != nil {
		_ = os.Remove(path)
		return fmt.Errorf("cannot close %s: %w", path, err)
	}
	return nil
}
